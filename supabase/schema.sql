create extension if not exists "pgcrypto";

-- ---------- Tables ----------

create table if not exists admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists categories (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  icon text default '💻',
  position int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references categories(id) on delete set null,
  name text not null,
  brand text,
  description text,
  price integer not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  warranty_months integer not null default 0,
  specs jsonb not null default '{}'::jsonb,
  images text[] not null default '{}',
  tags text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Prix d'achat : table séparée, jamais visible du public
create table if not exists product_costs (
  product_id uuid primary key references products(id) on delete cascade,
  cost integer not null default 0 check (cost >= 0)
);

create table if not exists offers (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  percent integer not null check (percent between 1 and 90),
  category_id uuid references categories(id) on delete cascade, -- null = tout le catalogue
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity,
  customer_name text not null,
  phone text not null,
  address text,
  city text,
  note text,
  payment_method text not null default 'livraison'
    check (payment_method in ('livraison', 'mobile_money')),
  status text not null default 'nouvelle'
    check (status in ('nouvelle', 'validee', 'livree', 'annulee')),
  total integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references orders(id) on delete cascade,
  product_id uuid references products(id) on delete set null,
  name text not null,
  unit_price integer not null,
  quantity integer not null check (quantity > 0)
);

create table if not exists subscribers (
  id uuid primary key default gen_random_uuid(),
  phone text not null unique,
  name text,
  opted_in boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists idx_products_category on products(category_id);
create index if not exists idx_orders_created on orders(created_at desc);
create index if not exists idx_orders_status on orders(status);
create index if not exists idx_items_order on order_items(order_id);

-- ---------- Fonctions utilitaires ----------

create or replace function is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (select 1 from admins where user_id = auth.uid());
$$;

-- Vue publique des produits actifs, avec remise et prix final calculés
create or replace view v_products as
select
  p.id, p.category_id, p.name, p.brand, p.description, p.price, p.stock,
  p.warranty_months, p.specs, p.images, p.tags, p.created_at,
  coalesce(d.percent, 0) as discount_percent,
  round(p.price * (100 - coalesce(d.percent, 0)) / 100.0)::int as final_price
from products p
left join lateral (
  select max(o.percent) as percent
  from offers o
  where o.is_active
    and now() between o.starts_at and o.ends_at
    and (o.category_id is null or o.category_id = p.category_id)
) d on true
where p.is_active;

grant select on v_products to anon, authenticated;

-- ---------- Création de commande (appelée par le public) ----------

create or replace function create_order(
  p_name text,
  p_phone text,
  p_address text,
  p_city text,
  p_note text,
  p_payment text,
  p_items jsonb
) returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order uuid;
  v_num bigint;
  v_total int := 0;
  it jsonb;
  prod record;
  qty int;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Panier vide';
  end if;
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_phone), '') = '' then
    raise exception 'Nom et téléphone obligatoires';
  end if;

  insert into orders (customer_name, phone, address, city, note, payment_method)
  values (trim(p_name), trim(p_phone), p_address, p_city, p_note,
          case when p_payment = 'mobile_money' then 'mobile_money' else 'livraison' end)
  returning id, order_number into v_order, v_num;

  for it in select * from jsonb_array_elements(p_items) loop
    qty := greatest(coalesce((it->>'quantity')::int, 1), 1);
    select * into prod from v_products where id = (it->>'product_id')::uuid;
    if not found then
      raise exception 'Produit indisponible';
    end if;
    if prod.stock < qty then
      raise exception 'Stock insuffisant pour %', prod.name;
    end if;
    insert into order_items (order_id, product_id, name, unit_price, quantity)
    values (v_order, prod.id, prod.name, prod.final_price, qty);
    v_total := v_total + prod.final_price * qty;
  end loop;

  update orders set total = v_total where id = v_order;

  insert into subscribers (phone, name)
  values (trim(p_phone), trim(p_name))
  on conflict (phone) do nothing;

  return json_build_object('order_id', v_order, 'order_number', v_num, 'total', v_total);
end;
$$;

grant execute on function create_order(text, text, text, text, text, text, jsonb) to anon, authenticated;

-- Inscription aux promotions (formulaire public)
create or replace function subscribe(p_phone text, p_name text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(trim(p_phone), '') = '' then
    raise exception 'Numéro obligatoire';
  end if;
  insert into subscribers (phone, name)
  values (trim(p_phone), nullif(trim(coalesce(p_name, '')), ''))
  on conflict (phone) do update set opted_in = true;
end;
$$;

grant execute on function subscribe(text, text) to anon, authenticated;

-- ---------- Changement de statut (admin) : gère le stock ----------

create or replace function set_order_status(p_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_current text;
begin
  if not is_admin() then
    raise exception 'Accès refusé';
  end if;
  if p_status not in ('nouvelle', 'validee', 'livree', 'annulee') then
    raise exception 'Statut invalide';
  end if;

  select status into v_current from orders where id = p_id for update;
  if v_current is null then
    raise exception 'Commande introuvable';
  end if;
  if v_current = p_status then
    return;
  end if;

  -- Sortie de stock à la première validation
  if v_current = 'nouvelle' and p_status in ('validee', 'livree') then
    update products p
       set stock = greatest(p.stock - oi.quantity, 0)
      from order_items oi
     where oi.order_id = p_id and oi.product_id = p.id;
  end if;

  -- Retour en stock si on annule une commande déjà validée
  if v_current in ('validee', 'livree') and p_status in ('annulee', 'nouvelle') then
    update products p
       set stock = p.stock + oi.quantity
      from order_items oi
     where oi.order_id = p_id and oi.product_id = p.id;
  end if;

  update orders set status = p_status where id = p_id;
end;
$$;

grant execute on function set_order_status(uuid, text) to authenticated;

-- ---------- Tableau de bord (admin) ----------

create or replace function dashboard_stats()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  r json;
begin
  if not is_admin() then
    raise exception 'Accès refusé';
  end if;

  select json_build_object(
    'sales_month', coalesce((select sum(total) from orders
        where status in ('validee', 'livree') and created_at >= date_trunc('month', now())), 0),
    'sales_week', coalesce((select sum(total) from orders
        where status in ('validee', 'livree') and created_at >= date_trunc('week', now())), 0),
    'orders_month', (select count(*) from orders where created_at >= date_trunc('month', now())),
    'pending_orders', (select count(*) from orders where status = 'nouvelle'),
    'margin_month', coalesce((
        select sum((oi.unit_price - coalesce(pc.cost, 0)) * oi.quantity)
        from order_items oi
        join orders o on o.id = oi.order_id
        left join product_costs pc on pc.product_id = oi.product_id
        where o.status in ('validee', 'livree') and o.created_at >= date_trunc('month', now())
      ), 0),
    'top_products', coalesce((
        select json_agg(t) from (
          select oi.name, sum(oi.quantity)::int as qty
          from order_items oi
          join orders o on o.id = oi.order_id
          where o.status in ('validee', 'livree') and o.created_at >= date_trunc('month', now())
          group by oi.name
          order by qty desc
          limit 5
        ) t), '[]'::json),
    'low_stock', coalesce((
        select json_agg(t) from (
          select id, name, stock from products
          where is_active and stock <= 3
          order by stock asc, name asc
          limit 8
        ) t), '[]'::json),
    'daily', coalesce((
        select json_agg(t) from (
          select to_char(d::date, 'DD/MM') as day,
                 coalesce(sum(o.total), 0)::int as total
          from generate_series(current_date - 6, current_date, interval '1 day') d
          left join orders o
            on o.created_at::date = d::date and o.status in ('validee', 'livree')
          group by d
          order by d
        ) t), '[]'::json)
  ) into r;

  return r;
end;
$$;

grant execute on function dashboard_stats() to authenticated;

